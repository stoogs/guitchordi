#!/usr/bin/env python3
"""Rasterise the OFL Noto Sans source into compact 4-bit device glyphs.
Generated header is checked in: ordinary builds need neither Pillow nor font tools.
"""
from pathlib import Path
from PIL import ImageFont
import hashlib,json
root=Path(__file__).resolve().parents[1]
source=root/'firmware/fonts/NotoSans.ttf'
chars=''.join(sorted(set(''.join(json.loads((root/'web/chords.json').read_text())['voicings'])+'0123456789XT%+-/FREEONOFFINST')))
lines=['// Generated by scripts/generate-display-font.py. Noto Sans, SIL OFL 1.1.',
       '// Copyright 2022 The Noto Project Authors. See fonts/OFL.txt.',
       '// Input SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest(),
       'typedef struct { uint16_t offset; int8_t x,y; uint8_t w,h,advance; } display_glyph;',
       'static const char display_chars[]='+json.dumps(chars)+';']
for size in [36,26,18,14,12]:
 font=ImageFont.truetype(str(source),size)
 axes=font.get_variation_axes()
 font.set_variation_by_axes([600 if a['name']==b'Weight' else a['default'] for a in axes])
 packed=[];entries=[]
 for c in chars:
  mask,(x,y)=font.getmask2(c,mode='L',anchor='ls')
  w,h=mask.size;data=[min(15,(p+8)//17) for p in mask]
  entries.append((len(packed),x,y,w,h,round(font.getlength(c))))
  packed.extend((data[i]<<4)|(data[i+1] if i+1<len(data) else 0) for i in range(0,len(data),2))
 lines+=['static const uint8_t display_pixels_%d[]={%s};'%(size,','.join(map(str,packed))),
         'static const display_glyph display_glyphs_%d[]={%s};'%(size,','.join('{'+','.join(map(str,e))+'}' for e in entries))]
 print(size,len(packed),'bytes')
(root/'firmware/display-font.h').write_text('\n'.join(lines)+'\n')
