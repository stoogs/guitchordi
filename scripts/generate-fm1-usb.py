"""Brand the pinned USB source without changing the retained upstream copy."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
def generate():
    source=(ROOT/'third_party/fm1-platform/firmware/src/usb.c').read_text()
    source=source.replace('#include "../hal/fm1_usb.h"','#include "fm1_usb.h"')
    for symbol,text in [('STR1','Stoogs'),('STR2','GuitChordi FM-1')]:
        pattern=rf'static const uint8_t {symbol}\[\] = \{{[^;]+;[^\n]* /\* X0X[^\n]*'
        data=[2+len(text)*2,3]+[v for c in text for v in (ord(c),0)]
        replacement=f'static const uint8_t {symbol}[] = {{'+', '.join(map(str,data))+'}; /* Guitchordi descriptor */'
        source,count=re.subn(pattern,replacement,source)
        if count!=1: raise SystemExit(f'Pinned USB descriptor changed: {symbol}')
    path=ROOT/'build/generated/gm_usb.c'
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text('/* Generated by scripts/generate-fm1-usb.py; upstream copyright retained. */\n'+source)
if __name__=='__main__': generate()
